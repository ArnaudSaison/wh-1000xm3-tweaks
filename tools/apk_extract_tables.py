#!/usr/bin/env python3
"""Regenerate xm3/tables.py from a jadx decompilation of Sony Sound Connect.

Reads only the enum constants (name -> byte value), which are the wire-format
identifiers. No Sony code is copied. Re-run it on a new app version and diff
the result to see protocol changes:

    jadx --no-res --deobf -d work/decompiled com.sony.songpal.mdr.apk
    uv run tools/apk_extract_tables.py work/decompiled/sources xm3/tables.py
"""
import re
import sys
from pathlib import Path

PKG = "com/sony/songpal/tandemfamily/message"
V1 = f"{PKG}/mdr/v1/table1"
V1P = f"{V1}/param"
VG = f"{PKG}/mdr/v1/table2/voiceguidance/param"

# Python constant name -> enum source file (relative to the sources root).
ENUMS = {
    "DATA_TYPE": f"{PKG}/DataType.java",
    "T1_COMMAND": f"{V1}/Command.java",
    "T2_COMMAND": f"{PKG}/mdr/v1/table2/Command.java",
    "FUNCTION_TYPE": f"{V1P}/FunctionType.java",
    "DEVICE_INFO_TYPE": f"{V1P}/DeviceInfoInquiredType.java",
    "UPDATE_INQUIRED_TYPE": f"{V1P}/UpdateInquiredType.java",
    "SYSTEM_INQUIRED_TYPE": f"{V1P}/SystemInquiredType.java",
    "NCASM_INQUIRED_TYPE": f"{V1P}/NcAsmInquiredType.java",
    "NCASM_EFFECT": f"{V1P}/NcAsmEffect.java",
    "NCASM_SETTING_TYPE": f"{V1P}/NcAsmSettingType.java",
    "ASM_SETTING_TYPE": f"{V1P}/AsmSettingType.java",
    "ASM_ID": f"{V1P}/AsmId.java",
    "BATTERY_INQUIRED_TYPE": f"{V1P}/BatteryInquiredType.java",
    "BATTERY_CHARGING_STATUS": f"{V1P}/BatteryChargingStatus.java",
    "EQEBB_INQUIRED_TYPE": f"{V1P}/EqEbbInquiredType.java",
    "EQ_PRESET": f"{V1P}/EqPresetId.java",
    "AUDIO_CODEC": f"{V1P}/AudioCodec.java",
    "ASSIGNABLE_KEY": f"{V1P}/AssignableSettingsKey.java",
    "ASSIGNABLE_KEY_TYPE": f"{V1P}/AssignableSettingsKeyType.java",
    "ASSIGNABLE_PRESET": f"{V1P}/AssignableSettingsPreset.java",
    "ASSIGNABLE_ACTION": f"{V1P}/AssignableSettingsAction.java",
    "ASSIGNABLE_FUNCTION": f"{V1P}/AssignableSettingsFunction.java",
    "AUTO_POWER_OFF": f"{V1P}/AutoPowerOffElementId.java",
    "VG_DETAILED_TYPE": f"{VG}/DetailedDataType.java",
    "VG_STATUS_TYPE": f"{VG}/StatusType.java",
    "VG_SWITCH": f"{VG}/SupportsSwitch.java",
    "MDR_LANGUAGE": None,  # located by search: it lives outside the message package
}

CONST = re.compile(r"^\s+([A-Z][A-Z0-9_]*)\(\s*(?:\(byte\)\s*(-?\d+)|BSON\.([A-Z_]+))")


def bson_constants(root: Path) -> dict[str, int]:
    text = (root / "org/bson/BSON.java").read_text(encoding="utf-8")
    found = re.findall(r"public static final byte ([A-Z_]+) = (-?\d+);", text)
    return {name: int(value) for name, value in found}


def parse_enum(path: Path, bson: dict[str, int]) -> dict[str, int]:
    out: dict[str, int] = {}
    in_enum = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if re.search(r"\benum \w+ \{", line):
            in_enum = True
            continue
        if not in_enum:
            continue
        match = CONST.match(line)
        if match:
            value = int(match[2]) if match[2] is not None else bson[match[3]]
            out[match[1]] = value & 0xFF
        if line.rstrip().endswith(";"):
            break
    if not out:
        raise SystemExit(f"no constants parsed from {path}")
    return out


def main() -> None:
    root, target = Path(sys.argv[1]), Path(sys.argv[2])
    bson = bson_constants(root)
    lang = next(root.glob("com/sony/**/MdrLanguage.java"))
    lines = [
        '"""GENERATED by tools/apk_extract_tables.py from the app\'s enum constants.',
        "",
        "Do not edit by hand; re-run the tool instead.",
        '"""',
        "",
    ]
    for name, rel in ENUMS.items():
        table = parse_enum(lang if rel is None else root / rel, bson)
        lines.append(f"{name} = {{")
        lines += [f'    "{key}": 0x{value:02X},' for key, value in table.items()]
        lines += ["}", ""]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {target}: {len(ENUMS)} tables")


if __name__ == "__main__":
    main()
